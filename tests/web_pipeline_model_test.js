const assert = require('node:assert/strict');
const P = require('../web/pipeline-model.js');
const base = () => P.fromSettings({enabled:true,products:['left_mono'],cadence_hz:5,delivery:'auto',preview:true,preview_cadence_hz:5});
const wired = {width:728,height:544,qualified:true,bytesPerSecond:64*1048576};
let graph = P.connect(base(),'out-1','rectified_stereo');
assert.deepEqual([...P.requirements(graph)],['cameras','rectification']);
graph = P.addOutput(graph,'depth');
assert.deepEqual(P.compile(graph,wired).products,['rectified_stereo','depth']);
assert.deepEqual([...P.requirements(graph)],['cameras','rectification','matcher','filter','depth']);
const rate=P.compile(graph,wired).bytesPerSecond;
graph=P.addOutput(graph,'depth');
assert.equal(P.compile(graph,wired).bytesPerSecond,rate,'fanout must not duplicate transport or device processing');
assert.throws(()=>P.removeOutput(graph,'cameras'),/cannot be removed/);
assert.throws(()=>P.connect(graph,'matcher','depth'),/protected/);
assert.throws(()=>P.connect(graph,'out-1','__proto__'),/supported/);
assert.throws(()=>P.normalize({...graph,edges:[['depth','cameras']]}),/Core nodes/);
assert.throws(()=>P.normalize({...graph,execute:'arbitrary'}),/Core nodes/);
assert.throws(()=>P.normalize({...graph,outputs:[{...graph.outputs[0],id:'cameras'}]}),/protected/);
assert.throws(()=>P.normalize({...graph,outputs:[graph.outputs[0],graph.outputs[0]]}),/unique/);
assert.throws(()=>P.normalize({...graph,outputs:[{...graph.outputs[0],name:'x'.repeat(41)}]}),/names/);
assert.throws(()=>P.normalize(JSON.parse('{"version":1,"__proto__":{},"outputs":[],"cadence":5,"delivery":"auto","preview":false,"previewCadence":5}')),/Core nodes/);
for(const cadence of [0,-1,61,NaN,Infinity])assert.throws(()=>P.normalize({...graph,cadence}),/cadence/);
assert.throws(()=>P.compile({...graph,delivery:'exact'},{...wired,qualified:false}),/qualified/);
assert.throws(()=>P.compile(graph,{...wired,rawEnabled:false}),/Raw delivery is off/);
assert.throws(()=>P.compile(graph,{...wired,supportedProducts:['left_mono']}),/not supported/);
assert.throws(()=>P.compile(graph,{...wired,width:0}),/dimensions/);
assert.throws(()=>P.compile(graph,{...wired,maxFrameBytes:1000}),/frame size/);
assert.throws(()=>P.compile(graph,{...wired,bytesPerSecond:1048576}),/resource budget/);
const dangling=P.addOutput(base());
assert.throws(()=>P.compile(dangling,wired),/Connect Output 2/);
dangling.outputs[1].enabled=false;assert.equal(P.compile(dangling,wired).products.length,1);
const off={...base(),outputs:[]};
assert.deepEqual(P.compile(off).products,[]);assert.equal(P.compile(off).enabled,false);
assert.equal(P.compile(off).bytesPerSecond,0);assert.equal(P.compile(off).preview,true);
let many=base();for(let i=1;i<P.MAX_OUTPUTS;i++)many=P.addOutput(many,'left_mono');
assert.throws(()=>P.addOutput(many,'depth'),/limited/);
assert.equal(P.compile(many,wired).products.length,1);
assert.equal(P.signature(many),P.signature(JSON.parse(JSON.stringify(many))));
assert.equal(base().outputs.length,1,'edits must not mutate other snapshots');
const disconnected=P.disconnect(base(),'out-1');
assert.equal(disconnected.outputs[0].product,null);
assert.equal(disconnected.outputs[0].enabled,false,'disconnect must be safe to apply without leaving an enabled dangling input');
assert.equal(P.compile(disconnected,wired).enabled,false);
assert.equal(disconnected.outputs.length,1,'disconnect preserves the output node');
const rewireBase=P.addOutput(base());
const reconnected=P.reconnect(rewireBase,'out-1','out-2','rectified_stereo');
assert.equal(reconnected.outputs[0].enabled,false);
assert.equal(reconnected.outputs[0].product,null);
assert.equal(reconnected.outputs[1].product,'rectified_stereo');
assert.deepEqual(P.compile(reconnected,wired).products,['rectified_stereo']);
assert.equal(rewireBase.outputs[0].product,'left_mono','reconnect must preserve undo snapshots');
assert.equal(P.reconnect(base(),'out-1','out-1','depth').outputs[0].product,'depth');
assert.throws(()=>P.reconnect(P.addOutput(base(),'depth'),'out-1','out-2','left_mono'),/already has a wire/);
assert.throws(()=>P.disconnect(base(),'cameras'),/protected/);
assert.throws(()=>P.reconnect(base(),'out-1','matcher','depth'),/protected/);
assert.throws(()=>P.reconnect(base(),'out-1','out-1','__proto__'),/supported/);
assert.throws(()=>P.reconnect(P.disconnect(base(),'out-1'),'out-1','out-1','depth'),/no longer exists/);
// Exercise the canvas admission gate independently of pointer gesture mechanics.
const fs=require('node:fs'),vm=require('node:vm');
const controller=fs.readFileSync(require('node:path').join(__dirname,'../web/pipeline.js'),'utf8');
const validator=controller.slice(controller.indexOf('  function connectionProduct('),controller.indexOf('  function reconnectWire('));
const admission={gestureCancelled:false,nodeIds:{encoder:'pipelineEncoderNode'},draft:P.addOutput(base()),sourceProduct:id=>({camera:'left_mono',rectifier:'left_rectified',filter:'confidence'}[id]),encoderAccepts:p=>p!=='confidence'};
vm.createContext(admission);vm.runInContext(validator,admission);
const input={source:'camera',sourceHandle:'products',target:'pipeline-out-1',targetHandle:'input'};
assert(admission.validConnection(input));
assert(!admission.validConnection({...input,target:'pipelineCamerasNode'}),'required camera input cannot be replaced');
assert(!admission.validConnection({...input,sourceHandle:'fixed-out'}),'fixed stage ports cannot start user wires');
assert(!admission.validConnection({...input,targetHandle:'fixed-in'}));
assert(!admission.validConnection({...input,source:'filter',target:'pipelineEncoderNode'}),'encoder must reject numeric-only products');
const edge={source:'rectifier',data:{editable:true,key:'out-1',kind:'output',product:'rectified_stereo'}};
assert.equal(admission.connectionProduct({...input,source:'rectifier'},edge),'rectified_stereo','moving a destination must preserve the current product');
assert.equal(admission.connectionProduct({...input,source:'rectifier'},{...edge,data:{...edge.data,handleType:'source'}}),'left_rectified','moving the source end chooses that port’s selected product');
assert(!admission.validConnection({...input,target:'pipelineEncoderNode'},edge));
assert(admission.validConnection({...input,target:'pipeline-out-2'},edge));
admission.draft=P.addOutput(base(),'depth');
assert(!admission.validConnection({...input,target:'pipeline-out-2'},edge),'an occupied destination must not be silently overwritten');
admission.gestureCancelled=true;
assert(!admission.validConnection(input),'Escape must invalidate an in-flight gesture');
console.log('Pipeline protected topology, branching, fanout, capability and resource safety tests passed');
