    def test_prepare_is_scoped_and_idempotent(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory); (root/"proc/device-tree").mkdir(parents=True); (root/"boot/firmware").mkdir(parents=True)
            (root/"proc/device-tree/model").write_bytes(b"Raspberry Pi 5 Model B\x00")
            config=root/"boot/firmware/config.txt"; config.write_text("arm_64bit=1\n")
            first=module.platform_prepare(root,True); second=module.platform_prepare(root,True)
            self.assertTrue(first["boot_config_changed"]); self.assertFalse(second["boot_config_changed"])
            self.assertEqual(config.read_text().count("BEGIN NUVO DEPTH"),1)
            self.assertTrue(config.with_name("config.txt.nuvo-backup").exists())

    def test_prepare_conditional_scope_conflicts_and_modprobe_reboot(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory)
            module.atomic_write(root/"proc/device-tree/model","Raspberry Pi 5 Model B",0o644)
            config=root/"boot/firmware/config.txt"
