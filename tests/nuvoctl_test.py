    def test_usb_status_reports_observed_state_without_provisioning(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory)
            self.assertEqual(module.usb_status(root),{"schema_version":1,"provisioned":False,
                "controller_present":False,"bound":False,"host_connected":False,"interfaces":[]})
            controller=root/'sys/class/udc/udc0';controller.mkdir(parents=True)
            self.assertTrue(module.usb_status(root)['controller_present'])
            gadget=root/'sys/kernel/config/usb_gadget/nuvo_depth';gadget.mkdir(parents=True)
            (gadget/'UDC').write_text('udc0\n');(controller/'state').write_text('configured\n')
            function=gadget/'functions/ecm.usb0';function.mkdir(parents=True)
            (function/'ifname').write_text('usb0\n');(function/'dev_addr').write_text('02:00:00:00:00:01\n')
            network=root/'sys/class/net/usb0';network.mkdir(parents=True)
            (network/'address').write_text('02:00:00:00:00:01\n')
            config=gadget/'configs/c.1';config.mkdir(parents=True)
            os.symlink('../../functions/ecm.usb0',config/'ecm.usb0')
            before={str(path.relative_to(root)):path.read_bytes() for path in root.rglob('*') if path.is_file()}
            observed=module.usb_status(root)
            self.assertTrue(observed['bound']);self.assertTrue(observed['host_connected'])
            self.assertEqual(observed['interfaces'],['usb0']);self.assertFalse(observed['provisioned'])
            self.assertEqual(before,{str(path.relative_to(root)):path.read_bytes() for path in root.rglob('*') if path.is_file()})
            self.assertFalse((root/'etc').exists(),'status created persistent USB configuration')
            (function/'ifname').unlink()
            self.assertEqual(module.usb_status(root)['interfaces'],['usb0'],'unambiguous function MAC can identify renamed interfaces')
            other=root/'sys/class/net/host_adapter';other.mkdir()
            (other/'address').write_text('02:00:00:00:00:01\n')
            self.assertEqual(module.usb_status(root)['interfaces'],[],'ambiguous network evidence must not invent device-mode interface')
            (config/'ecm.usb0').unlink()
            self.assertEqual(module.usb_status(root)['interfaces'],[],'unlinked functions are not active USB interfaces')
            (controller/'state').write_text('addressed\n')
            self.assertIsNone(module.usb_status(root)['host_connected'])
            (controller/'state').write_text('suspended\n')
            self.assertIsNone(module.usb_status(root)['host_connected'],'USB suspend is not evidence of an unplugged host')
            (controller/'state').write_text('not attached\n')
            self.assertFalse(module.usb_status(root)['host_connected'])
            (controller/'state').write_text('unrecognized\n')
            self.assertIsNone(module.usb_status(root)['host_connected'])
            (gadget/'UDC').unlink()
            self.assertIsNone(module.usb_status(root)['bound'],'unreadable existing gadget state is unknown')

